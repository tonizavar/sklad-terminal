-- Shared terminal mode requested by the owner: no login, no user roles.
-- No working devices or history are deleted. Direct table writes are replaced by checked RPCs.
create schema if not exists scanner_private;
revoke all on schema scanner_private from public, anon, authenticated;
grant usage on schema scanner_private to anon, authenticated;
create table if not exists scanner_private.operations (
  id text primary key, payload jsonb not null, result jsonb not null,
  created_at timestamptz not null default now()
);
alter table scanner_private.operations add column if not exists operator_id uuid;
create table if not exists scanner_private.backups (
  name text primary key, snapshot jsonb not null, created_at timestamptz not null default now()
);
alter table scanner_private.backups add column if not exists hidden_at timestamptz;
revoke all on all tables in schema scanner_private from public, anon, authenticated;
alter table scanner_private.operations enable row level security;
alter table scanner_private.backups enable row level security;

create table if not exists public.devices (
  serial text primary key, model text, status text default 'free', holder text default '',
  issued_at text, last_move text, shift text
);
alter table public.devices add column if not exists version text not null default 'initial';
alter table public.devices add column if not exists defect text not null default '';
alter table public.devices add column if not exists deleted_at timestamptz;
create table if not exists public.movements (
  id bigint generated by default as identity primary key,
  created_at text, serial text, action text, worker text, event_id text
);
alter table public.movements add column if not exists event_id text;
alter table public.movements add column if not exists operator_id uuid;
alter table public.movements add column if not exists terminal_id text;
alter table public.movements add column if not exists occurred_at timestamptz;
alter table public.movements add column if not exists received_at timestamptz not null default now();
